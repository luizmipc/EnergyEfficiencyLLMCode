from typing import List


class Solution:
    def solveSudoku(self, board: List[List[str]]) -> None:
        n = 9
        rows = [[False] * 10 for _ in range(n)]
        cols = [[False] * 10 for _ in range(n)]
        boxes = [[False] * 10 for _ in range(n)]

        for r in range(n):
            for c in range(n):
                ch = board[r][c]
                if ch != ".":
                    d = int(ch)
                    b = 3 * (r // 3) + c // 3
                    rows[r][d] = cols[c][d] = boxes[b][d] = True

        def solve(row, col):
            if row == n:
                return True
            if col == n:
                return solve(row + 1, 0)

            if board[row][col] == ".":
                b = 3 * (row // 3) + col // 3
                for d in range(1, 10):
                    if not rows[row][d] and not cols[col][d] and not boxes[b][d]:
                        board[row][col] = str(d)
                        rows[row][d] = cols[col][d] = boxes[b][d] = True

                        if solve(row, col + 1):
                            return True

                        board[row][col] = "."
                        rows[row][d] = cols[col][d] = boxes[b][d] = False
                return False
            else:
                return solve(row, col + 1)

        solve(0, 0)

